import Foundation

// Higher-order generators built by composing other generators. As with the primitives, concrete
// result types are named explicitly (`Gen<[A]>` etc.) so the construction does not bind to the
// extension's free generic `A`.

public extension Stateful where S == AnyRandomNumberGenerator {
    /// An array of exactly `count` independently-generated values (clamped to `>= 0`).
    func array(ofCount count: Int) -> Gen<[A]> {
        // swiftlint:disable:next closure_ignoring_args
        Gen<[A]> { rng in (0..<max(0, count)).map { _ in self(&rng) } } // side effect — rng mutated
    }

    /// An array whose length is itself generated by `count`.
    func array(ofCount count: Gen<Int>) -> Gen<[A]> {
        count.flatMap { length in self.array(ofCount: length) }
    }

    /// `nil` or a generated value, with equal probability.
    func optional() -> Gen<A?> {
        Gen<A?> { rng in Bool.random(using: &rng) ? Optional(self(&rng)) : nil }
    }

    /// Uniformly picks one of the given generators and runs it.
    ///
    /// `NonEmpty` guarantees there is always at least one choice, so this never traps.
    static func one(of generators: NonEmpty<Gen<A>>) -> Gen<A> {
        Gen<A> { rng in
            let choices = generators.toArray
            return choices[Int.random(in: 0..<choices.count, using: &rng)](&rng)
        }
    }

    /// Picks one of the given generators with probability proportional to its weight.
    ///
    /// Each weight is clamped to `>= 1`, so the total is always positive and a pair is always
    /// chosen — there is no zero-total trap. To exclude a generator, omit its pair rather than
    /// giving it weight zero.
    static func frequency(_ pairs: NonEmpty<(Int, Gen<A>)>) -> Gen<A> {
        Gen<A> { rng in
            let weighted = pairs.toArray.map { (max(1, $0.0), $0.1) }
            let total = weighted.reduce(0) { $0 + $1.0 }
            var remaining = Int.random(in: 1...total, using: &rng)
            for (weight, generator) in weighted {
                if remaining <= weight { return generator(&rng) }
                remaining -= weight
            }
            return weighted[weighted.count - 1].1(&rng)
        }
    }
}

// MARK: - Characters & strings

public extension Stateful where S == AnyRandomNumberGenerator {
    /// A uniform random `Character` drawn from `characters`.
    static func character(in characters: NonEmpty<Character>) -> Gen<Character> where A == Character {
        let choices = characters.toArray
        return Gen<Character> { rng in choices[Int.random(in: 0..<choices.count, using: &rng)] }
    }

    /// A uniform random ASCII letter (`A–Z`, `a–z`).
    static func letter() -> Gen<Character> where A == Character {
        character(in: NonEmpty(head: "A", tail: Array("BCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz")))
    }

    /// A uniform random decimal digit character (`0–9`).
    static func digit() -> Gen<Character> where A == Character {
        character(in: NonEmpty(head: "0", tail: Array("123456789")))
    }

    /// A uniform random alphanumeric character (`0–9`, `A–Z`, `a–z`).
    static func alphanumeric() -> Gen<Character> where A == Character {
        character(in: NonEmpty(
            head: "0",
            tail: Array("123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz")
        ))
    }

    /// A `String` of `count` characters, each drawn from `character`.
    static func string(of character: Gen<Character>, count: Gen<Int>) -> Gen<String> where A == String {
        character.array(ofCount: count).map { String($0) }
    }
}
